#!/usr/bin/env node
// Writes gem/GEM_INSTRUCTIONS.md: the static GemInWeb primer for a Gemini Gem or AI Studio system instructions.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { staticPrimer } from '../core/primer.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'gem', 'GEM_INSTRUCTIONS.md');
const primer = staticPrimer();
const fence = '`'.repeat(Math.max(4, ...[...primer.matchAll(/`+/g)].map((m) => m[0].length + 1)));

const text = `# GemInWeb instructions (for a Gem / AI Studio system instructions)

Generated by \`npm run gen:gem\` (scripts/gen-gem.mjs). Do not edit by hand.

## How to use

- **Gemini web**: gemini.google.com → **Gem manager** → **New Gem** → paste everything inside the block below into **Instructions** and save. Then start new chats from that Gem.
- **Google AI Studio**: aistudio.google.com → new chat → paste everything inside the block below into **System instructions**. (The extension panel's "시스템 지침에 넣기" (Put into system instructions) button does this too.)
- With the protocol in the instructions, set primerMode = \`context\` in the extension options: starting a task then only sends a short \`[DevSpace context]\` block (time, OS, workspace).
- Copy from the first line \`[GemInWeb protocol v1]\` to the last line. Do not copy the backtick fence lines that wrap the block.

## Paste this (${primer.length} chars)

${fence}text
${primer}
${fence}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, text, 'utf8');
console.log(`Wrote ${out} (${primer.length} chars of primer)`);
